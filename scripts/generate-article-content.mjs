import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import matter from 'gray-matter'

const rootDir = process.cwd()
const articlesDir = path.join(rootDir, 'app', '_articles')
const outputFile = path.join(rootDir, 'lib', 'articles', 'content.generated.ts')

function toKey(category, filename) {
  return `${category}/${filename.replace(/\.mdx$/, '')}`
}

async function main() {
  const entries = {}
  const categories = await readdir(articlesDir, { withFileTypes: true })

  for (const categoryEntry of categories) {
    if (!categoryEntry.isDirectory()) continue

    const category = categoryEntry.name
    const categoryDir = path.join(articlesDir, category)
    const files = await readdir(categoryDir, { withFileTypes: true })

    for (const fileEntry of files) {
      if (!fileEntry.isFile() || !fileEntry.name.endsWith('.mdx')) continue

      const filePath = path.join(categoryDir, fileEntry.name)
      const fileContent = await readFile(filePath, 'utf8')
      entries[toKey(category, fileEntry.name)] = matter(fileContent).content
    }
  }

  const sortedEntries = Object.fromEntries(
    Object.entries(entries).sort(([a], [b]) => a.localeCompare(b))
  )

  const output = [
    '// This file is generated by scripts/generate-article-content.mjs.',
    '// Do not edit it directly; edit app/_articles/*.mdx instead.',
    '',
    `export const articleContentByKey = ${JSON.stringify(sortedEntries, null, 2)} as const`,
    '',
  ].join('\n')

  await writeFile(outputFile, output, 'utf8')
  console.log(`Generated ${Object.keys(sortedEntries).length} article bodies in ${path.relative(rootDir, outputFile)}`)
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
